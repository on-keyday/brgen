#!/usr/bin/env python3
"""nodes.json から nast アリーナの線上表現を .bgn として生成する。

nast の状態 (アリーナ + side table) を brgen 自身で符号化できるかを測るための
もの。出力を src2json -> json2cpp2 に通すと encode/decode が生えてくる。
EBM が extended_binary_module.bgn で自分を定義しているのと同じ形。

  python src/core/nast/wiregen.py [-o <path>]

既定の出力先は src/core/nast/nast_wire.bgn。EBM が extended_binary_module.bgn と
生成された .hpp を両方 commit しているのと同じで、.bgn と .hpp は追跡する。
中間の .json だけ ignore/ に置く。

対応:
  Node<X>          -> Ref                       (u32 の添字)
  vector<Node<X>>  -> <name>_len :u32 + 配列
  string           -> Ref                       (文字列表への添字)
  bool             -> u8
  size / uint32    -> u32
  lexer::Loc       -> format Loc
  enum             -> .bgn の enum そのまま

失われるもの: Node<Expr> と Node<Statement> はどちらも Ref になるので、
phantom type による静的な取り違え防止は線上では効かない。読み戻すときに
NodeHeader.type で検査する側の仕事になる。
"""

import argparse
import io
import json
import os

REPO = os.path.dirname(os.path.abspath(__file__))
for _ in range(3):
    REPO = os.path.dirname(REPO)


def enum_members(e):
    """nast の enum は layers / enums / extra に分かれて入っている。"""
    out = []
    for layer in e.get("layers", []):
        for m in layer.get("enums", []):
            out.append(m["name"])
    for m in e.get("enums", []):
        out.append(m["name"])
    for m in e.get("extra", []):
        out.append(m if isinstance(m, str) else m["name"])
    return out


def snake(name):
    return name[0].lower() + "".join("_" + c.lower() if c.isupper() else c for c in name[1:])


def wire_type(t, name):
    if t.startswith("Node<"):
        return [name + " :Ref"]
    if t.startswith("vector<Node<"):
        return [name + "_len :u32", name + " :[" + name + "_len]Ref"]
    if t == "string":
        return [name + " :Ref"]
    if t == "bool":
        return [name + " :u8"]
    if t in ("size", "uint32"):
        return [name + " :u32"]
    if t == "lexer::Loc":
        return [name + " :Loc"]
    return [name + " :" + t]  # enum


def generate(schema):
    by = {n["name"]: n for n in schema["nodes"]}
    has_child = set()
    for n in schema["nodes"]:
        if "derive" in n:
            has_child.add(n["derive"])
    concrete = [n for n in schema["nodes"] if n["name"] not in has_child]

    def all_fields(n):
        out = []
        if "derive" in n:
            out += all_fields(by[n["derive"]])
        return out + list(n.get("fields", []))

    o = []
    w = o.append
    w("# Code generated by src/core/nast/wiregen.py from nodes.json; DO NOT EDIT.")
    w('config.cpp.namespace = "brgen::nast::wire"')
    w("")
    w("format Ref:")
    w("    id :u32")
    w("")
    w("format Loc:")
    w("    begin :u32")
    w("    end :u32")
    w("    file :u32")
    w("    line :u32")
    w("    col :u32")
    w("")
    w("format StringEntry:")
    w("    len :u32")
    w("    data :[len]u8")
    w("")

    for e in schema["enums"]:
        w("enum " + e["name"] + ":")
        w("    :u8")
        for m in enum_members(e):
            w("    " + m)
        w("")

    w("enum NodeKind:")
    w("    :u32")
    for n in concrete:
        w("    " + n["name"])
    w("")

    # 判別子は node_kind。kind にすると SpecialLiteral.kind の union getter と
    # 名前が衝突して生成された C++ が通らない。
    w("format Node:")
    w("    node_kind :NodeKind")
    w("    loc :Loc")
    w("    match node_kind:")
    for n in concrete:
        fs = all_fields(n)
        w("        NodeKind." + n["name"] + ":")
        if not fs:
            w("            ..")
            continue
        for f in fs:
            for line in wire_type(f["type"], f["name"]):
                w("            " + line)
    w("")

    # side table。アリーナと別に持っている解析結果も同じ規則で書ける。
    # 各表は「キー (Ref) + 表の持つフィールド」の並び。フィールドを持たない
    # flag 表 (IsMutated) はキーだけの列になる。
    tables = []
    for t in schema["side_tables"]:
        name = t["name"]
        tables.append(name)
        w("format " + name + "Entry:")
        w("    key :Ref")
        fs = t.get("fields", [])
        if not fs:
            w("    ..")
        for f in fs:
            for line in wire_type(f["type"], f["name"]):
                w("    " + line)
        w("")
        w("format " + name + "Table:")
        w("    len :u32")
        w("    entries :[len]" + name + "Entry")
        w("")

    w("")
    w("format NastModule:")
    w('    magic :"NAST"')
    w("    version :u8")
    w("    strings_len :u32")
    w("    strings :[strings_len]StringEntry")
    w("    nodes_len :u32")
    w("    nodes :[nodes_len]Node")
    w("    root :Ref")
    for name in tables:
        w("    " + snake(name) + " :" + name + "Table")
    w("")
    return o, len(concrete)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--schema", default=os.path.join(REPO, "src", "core", "nast", "nodes.json"))
    p.add_argument("-o", "--output",
                   default=os.path.join(REPO, "src", "core", "nast", "nast_wire.bgn"))
    args = p.parse_args()

    schema = json.load(io.open(args.schema, encoding="utf-8"))
    lines, concrete = generate(schema)
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    io.open(args.output, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("{}: {} lines, {} node kinds".format(args.output, len(lines), concrete))


if __name__ == "__main__":
    main()
