import sys
import os
sys.path.insert(0,os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from gen import Writer
from gen import Schema

def emit_backend_knobs(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/code_writer.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"lang.hpp\"")
    w.line("#include <functional>")
    w.line("#include \"invocable.hpp\"")
    w.line("#include \"common.hpp\"")
    w.line("namespace brgen::nast::backend {")
    w.line("    template <class R = CodeWriter>")
    w.line("    struct Knobs {")
    for node in s.concrete_nodes():
        w.line("        std::function<result<R>(BaseContext&, Node<",node["name"],">)> custom_",node["name"],";")
        w.line("        template <class T,invocable_r<result<R>,Context<R,T>&,Node<",node["name"],">> F>")
        w.line("        void bind_",str(node["name"]),"(Context<R,T>&,F&& f) {")
        w.line("            custom_",str(node["name"])," = [f = std::forward<F>(f)](BaseContext& c,Node<",node["name"],"> n) {")
        w.line("                   auto l = c.l.template as<T>();")
        w.line("                   if (!l) { return unexpect_error(\"expect language {} but got {}\",T::lang_name,l.lang_name()); }")
        w.line("                   Context<R,T> new_c{c,*l};")
        w.line("                   return f(new_c,n);")
        w.line("            };")
        w.line("        }")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()

def emit_backend_defaults(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/code_writer.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"lang.hpp\"")
    w.line("#include <functional>")
    w.line("#include \"invocable.hpp\"")
    w.line("#include \"common.hpp\"")
    for node in s.concrete_nodes():
        w.line("#if __has_include(\"defaults/emit_",node["name"],".hpp\")")
        w.line("#include \"defaults/emit_",node["name"],".hpp\"")
        w.line("#else")
        w.line("template<> struct DefaultHandler<",node["name"],"> {")
        w.line("    constexpr result<CodeWriter> operator()()")
        w.line("#end")


    w.line("namespace brgen::nast::backend {")
    w.line("    struct DefaultBehavior {")
    for node in s.concrete_nodes():
        w.line("        std::function<result<CodeWriter>(BaseContext&, Node<",node["name"],">)> custom_",node["name"],";")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()
