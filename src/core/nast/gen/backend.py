def emit_backend_config(s :Schema) -> str:
    """値 knob を CommonConfig として出す。

    knob は **そのノードのハンドラに付いた追加のつまみ**なので、宣言もノードの
    隣 (nodes.json の `knobs`) に置く。出力もノードごとに入れ子にして、
    どのハンドラの話なのかを名前で分かるようにする:

        ctx.config().IsLittleEndian.native_endian_check

    フックを書かずに済ませられるものはここに置く。言語差の大半は「どう綴るか」
    であって「どう辿るか」ではないので、宣言で吸収できるものは宣言で持つ
    (rebrgen の実測: 既定フック 103 本に対して言語側のフックは 3〜30 本、
    一方で entry_before での knob 設定は 50〜83 件)。

    1 つの言語にしか無いものはここではなくその言語の LangConfig に置く
    (`ctx.lang_config()` から読める)。3 言語で同じものを書いたらここへ上げる
    — ADR 0016 と同じ線引き。
    """
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include <cstdint>")
    w.line("#include <string>")
    w.line("namespace brgen::nast::backend {")
    w.line("    template <class R>")
    w.line("    struct BaseContext;")
    w.line("    template <class C>")
    w.line("    struct Invoker;")
    w.line("")
    w.line("    // 未対応のノードに当たったときどうするか。ノードに紐づかない")
    w.line("    // 唯一の設定で、--unhandled から来る。")
    w.line("    enum class UnhandledMode : std::uint8_t {")
    w.line("        error,")
    w.line("        dummy,")
    w.line("        ignore,")
    w.line("    };")
    w.line("")
    w.line("    struct CommonConfig {")
    w.line("        UnhandledMode unhandled_mode = UnhandledMode::dummy;")
    for node in s.concrete_nodes():
        knobs = node.get("knobs")
        if not knobs:
            continue
        w.line("")
        w.line("        // ", node["name"], " のハンドラのつまみ。")
        w.line("        struct ", node["name"], "Knobs {")
        for k in knobs:
            if k.get("description"):
                w.line("            // ", k["description"])
            w.line("            ", k["type"], " ", k["name"], " = ", k["default"], ";")
        w.line("        } ", node["name"], ";")
    w.line("")
    w.line("       private:")
    w.line("        template <class R>")
    w.line("        friend struct BaseContext;")
    w.line("        template <class C>")
    w.line("        friend struct Invoker;")
    w.line("        bool inner_default = false;")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()


def emit_backend_invoke(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/error.h\"")
    w.line("#include \"../../common/expected.h\"")
    w.line("namespace brgen::nast::backend {")
    w.line("template<class Context>")
    w.line("struct Invoker {")
    w.line("protected:")
    w.line("    template<class R>")
    w.line("    expected<R> invoke_custom(NodeAny n) {")
    w.line("        auto& c = static_cast<Context&>(*this);")
    w.line("        switch(n.type()) {")
    for node in s.concrete_nodes():
      w.line("        case NodeType::",node["name"],": if(c.n.custom_",node["name"],") { c.c.inner_default = false; return  c.n.custom_",node["name"],"(c,n.template as_any<",node["name"],">()); } else { c.c.inner_default = true; return c.d.default_",node["name"],"(c,n.template as_any<",node["name"],">()); }")
    w.line("        default: return unexpect_loc_error(n,\"unexpected node type: {}\",to_string(n.type()));")
    w.line("        }")
    w.line("    }")
    w.line("    template<class R>")
    w.line("    expected<R> invoke_default(NodeAny n) {")
    w.line("        auto& c = static_cast<Context&>(*this);")
    w.line("        switch(n.type()) {")
    for node in s.concrete_nodes():
      w.line("        case NodeType::",node["name"],": { c.n.inner_default = true; return c.d.default_",node["name"],"(c,n.template as_any<",node["name"],">()); }")
    w.line("        default: return unexpect_loc_error(n,\"unexpected node type: {}\",to_string(n.type()));")
    w.line("        }")
    w.line("    }")
    w.line("};")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()


def emit_backend_knobs(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/code_writer.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"lang.hpp\"")
    w.line("#include <functional>")
    w.line("#include \"invocable.hpp\"")
    w.line("#include \"common.hpp\"")
    w.line("namespace brgen::nast::backend {")
    w.line("    template <class R = CodeWriter>")
    w.line("    struct Knobs {")
    for node in s.concrete_nodes():
        w.line("        std::function<expected<R>(BaseContext<R>&, Node<",node["name"],">)> custom_",node["name"],";")
        w.line("        template <class T,invocable_r<expected<R>,Context<R,T>&,Node<",node["name"],">> F>")
        w.line("        void bind_",str(node["name"]),"(Context<R,T>&,F&& f) {")
        w.line("            custom_",str(node["name"])," = [f = std::forward<F>(f)](BaseContext<R>& c,Node<",node["name"],"> n) -> expected<R> {")
        w.line("                   auto l = c.l.template as<T>();")
        w.line("                   if (!l) { return unexpect_loc_error(n,\"expect language {} but got {}\",T::lang_name,c.l.lang_name()); }")
        w.line("                   Context<R,T> new_c{c,*l};")
        w.line("                   return f(new_c,n);")
        w.line("            };")
        w.line("        }")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()

def emit_backend_defaults(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/code_writer.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"lang.hpp\"")
    w.line("#include <functional>")
    w.line("#include \"invocable.hpp\"")
    w.line("#include \"common.hpp\"")
    w.line("#include \"defaults/handler.hpp\"")
    for node in s.concrete_nodes():
        w.line("#if __has_include(\"defaults/emit_",node["name"],".hpp\")")
        w.line("template<class R>")
        w.line("struct brgen::nast::backend::DefaultHandler<R,brgen::nast::",node["name"],"> {")
        w.line("    constexpr brgen::nast::expected<R> operator()(BaseContext<R>&,Node<",node["name"],">);")
        w.line("};")
        w.line("#define DEFINE_VISITOR(dummy) \\")
        w.line("    template<class R> \\")
        w.line("    constexpr brgen::nast::expected<R> brgen::nast::backend::DefaultHandler<R,brgen::nast::",node["name"],">::operator()(BaseContext<R>& ctx,Node<",node["name"],"> node)")
        w.line("#include \"defaults/emit_",node["name"],".hpp\"")
        w.line("#undef DEFINE_VISITOR")
        w.line("#else")
        w.line("template<class R>")
        w.line("struct brgen::nast::backend::DefaultHandler<R,brgen::nast::",node["name"],"> {")
        w.line("    constexpr brgen::nast::expected<R> operator()(BaseContext<R>& ctx,Node<",node["name"],"> node) {")
        w.line("          DEFAULT_HANDLER()")
        w.line("          ON_CODEGEN_DEFAULT()")
        w.line("          ON_UNHANDLED_DEFAULT()")
        w.line("    }")
        w.line("};")
        w.line("#endif")


    w.line("namespace brgen::nast::backend {")
    w.line("    template<class R>")
    w.line("    struct DefaultBehavior {")
    for node in s.concrete_nodes():
        w.line("        DefaultHandler<R,",node["name"],"> default_",node["name"],";")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()
