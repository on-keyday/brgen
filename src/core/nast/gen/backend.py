def emit_backend_invoke(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"../../common/expected.h\"")
    w.line("namespace brgen::nast::backend {")
    w.line("template<class Context>")
    w.line("struct Invoker {")
    w.line("protected:")
    w.line("    template<class R>")
    w.line("    result<R> invoke_impl(NodeAny n) {")
    w.line("        auto& c = static_cast<Context&>(*this);")
    w.line("        switch(n.type()) {")
    for node in s.concrete_nodes():
      w.line("        case NodeType::",node["name"],": return c.n.custom_",node["name"]," ? c.n.custom_",node["name"],"(c,n.template as_any<",node["name"],">()) : c.d.default_",node["name"],"(c,n.template as_any<",node["name"],">());")
    w.line("        default: return unexpect_loc_error(n.ref(c.a).loc(),\"unexpected node type: {}\",to_string(n.type()));")
    w.line("        }")
    w.line("    }")
    w.line("};")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()


def emit_backend_knobs(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/code_writer.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"lang.hpp\"")
    w.line("#include <functional>")
    w.line("#include \"invocable.hpp\"")
    w.line("#include \"common.hpp\"")
    w.line("namespace brgen::nast::backend {")
    w.line("    template <class R = CodeWriter>")
    w.line("    struct Knobs {")
    for node in s.concrete_nodes():
        w.line("        std::function<result<R>(BaseContext<R>&, Node<",node["name"],">)> custom_",node["name"],";")
        w.line("        template <class T,invocable_r<result<R>,Context<R,T>&,Node<",node["name"],">> F>")
        w.line("        void bind_",str(node["name"]),"(Context<R,T>&,F&& f) {")
        w.line("            custom_",str(node["name"])," = [f = std::forward<F>(f)](BaseContext<R>& c,Node<",node["name"],"> n) -> result<R> {")
        w.line("                   auto l = c.l.template as<T>();")
        w.line("                   if (!l) { return unexpect_loc_error(n.ref(c.a).loc(),\"expect language {} but got {}\",T::lang_name,c.l.lang_name()); }")
        w.line("                   Context<R,T> new_c{c,*l};")
        w.line("                   return f(new_c,n);")
        w.line("            };")
        w.line("        }")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()

def emit_backend_defaults(s :Schema) -> str:
    w = Writer()
    w.line("/*licnese*/")
    w.line("// Code generated by src/core/ast/nodegen.py. DO NOT EDIT.")
    w.line("#pragma once")
    w.line("#include \"../node/nodes.h\"")
    w.line("#include \"../node/code_writer.h\"")
    w.line("#include \"../../common/error.h\"")
    w.line("#include \"lang.hpp\"")
    w.line("#include <functional>")
    w.line("#include \"invocable.hpp\"")
    w.line("#include \"common.hpp\"")
    for node in s.concrete_nodes():
        w.line("#if __has_include(\"defaults/emit_",node["name"],".hpp\")")
        w.line("template<class R>")
        w.line("struct brgen::nast::backend::DefaultHandler<R,brgen::nast::",node["name"],"> {")
        w.line("    constexpr result<R> operator()(BaseContext<R>&,Node<",node["name"],">);")
        w.line("};")
        w.line("#define DEFINE_VISITOR(dummy) \\")
        w.line("    template<class R> \\")
        w.line("    constexpr brgen::result<R> brgen::nast::backend::DefaultHandler<R,brgen::nast::",node["name"],">::operator()(BaseContext<R>& ctx,Node<",node["name"],"> node)")
        w.line("#include \"defaults/emit_",node["name"],".hpp\"")
        w.line("#undef DEFINE_VISITOR")
        w.line("#else")
        w.line("template<class R>")
        w.line("struct brgen::nast::backend::DefaultHandler<R,brgen::nast::",node["name"],"> {")
        w.line("    constexpr result<R> operator()(BaseContext<R>&,Node<",node["name"],">) {")
        w.line("          return {};")
        w.line("    }")
        w.line("};")
        w.line("#endif")


    w.line("namespace brgen::nast::backend {")
    w.line("    template<class R>")
    w.line("    struct DefaultBehavior {")
    for node in s.concrete_nodes():
        w.line("        DefaultHandler<R,",node["name"],"> default_",node["name"],";")
    w.line("    };")
    w.line("} // namespace brgen::nast::backend")
    return w.getvalue()
