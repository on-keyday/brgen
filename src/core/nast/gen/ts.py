"""nodes.json から TypeScript のノードライブラリを生成する。

nast_dump が吐く JSON (arena + side tables) を LSP サーバー側で読むためのもので、
C++ 側の nodes.h と対になる。ast2ts が src2json に対して果たす役と同じ。

規約 (dump.cpp / nodes.h の as_json と揃えてある):

- ノード参照は unique_id = (NodeType 値 << 32) | id の number。
  下 32bit が 0 なら null。NodeType 値は 2^19 未満なので全体は 2^53 未満に
  収まり、JS の Number で正確に持てる
- enum は正準名 (nodes.json の name) の文字列
- arena は { headers: [...], "data_<Kind>": [...] }。headers[id - 1] が
  そのノードのヘッダで、data_index が種別ごとの pool を指す
- side table は { "<id>": value } のオブジェクト (id は下 32bit の生の値)
"""

import re

from .schema import Schema
from .writer import Writer

PROLOGUE = (
    "/*license*/\n"
    '// Code generated by "nodegen.py"; DO NOT EDIT.\n'
    "// edit src/core/nast/nodes.json instead.\n"
    "\n"
)

_SCALARS = {
    "string": "string",
    "bool": "boolean",
    "size": "number",
    "uint32": "number",
    "lexer::Loc": "Loc",
}


def _ts_type(t: str) -> str:
    m = re.fullmatch(r"vector<(.+)>", t)
    if m:
        return _ts_type(m.group(1)) + "[]"
    if re.fullmatch(r"Node<.+>", t):
        return "NodeId"
    return _SCALARS.get(t, t)


def _emit_prelude(w: Writer) -> None:
    w.write(
        "export type NodeId = number;\n"
        "\n"
        "export interface Loc {\n"
        "    pos: { begin: number; end: number };\n"
        "    file: number;\n"
        "    line: number;\n"
        "    col: number;\n"
        "}\n"
        "\n"
        "// unique_id の下 32bit がアリーナ内の id。0 なら null 参照。\n"
        "export function idIndex(id: NodeId): number {\n"
        "    return id % 0x100000000;\n"
        "}\n"
        "\n"
        "export function isNullId(id: NodeId | null | undefined): boolean {\n"
        "    return id === null || id === undefined || idIndex(id) === 0;\n"
        "}\n"
        "\n"
    )


def _emit_enums(w: Writer, schema: Schema) -> None:
    for enum in schema.enums:
        names = [m["name"] for m in enum["enums"]]
        w.write("export type ", enum["name"], " =\n    ")
        w.write(" |\n    ".join(f'"{n}"' for n in names))
        w.write(";\n\n")


def _emit_enum_display(w: Writer, schema: Schema) -> None:
    """表示用の代表表記。alt_names があればその先頭 (演算子なら記号)。"""
    import json as _json
    w.write("export const ENUM_DISPLAY = {\n")
    for enum in schema.enums:
        w.write("    ", enum["name"], ": {\n")
        for m in enum["enums"]:
            w.write("        ", _json.dumps(m["name"]), ": ",
                    _json.dumps(Schema.primary_name(m)), ",\n")
        w.write("    },\n")
    w.write("} as const;\n\n")


def _emit_kinds(w: Writer, schema: Schema) -> None:
    names = [n["name"] for n in schema.nodes]
    w.write("export type NodeKind =\n    ")
    w.write(" |\n    ".join(f'"{n}"' for n in names))
    w.write(";\n\n")
    w.write("export const NODE_KINDS: readonly NodeKind[] = [\n")
    for n in names:
        w.write(f'    "{n}",\n')
    w.write("];\n\n")

    # NodeType の数値。unique_id の上位 32bit がこれ。
    width = schema.derive_bit_width
    w.write("export const NODE_VALUE: Readonly<Record<NodeKind, number>> = {\n")
    for i, node in enumerate(schema.nodes):
        w.write(f'    {node["name"]}: {(i << width) | schema.derive_bits(node)},\n')
    w.write("};\n\n")

    w.write(
        "export function makeId(kind: NodeKind, index: number): NodeId {\n"
        "    return NODE_VALUE[kind] * 0x100000000 + index;\n"
        "}\n"
        "\n"
    )

    # 継承の答え合わせ用。is_derived<T>() に当たる。
    w.write("export const ANCESTORS: Readonly<Record<NodeKind, readonly NodeKind[]>> = {\n")
    for node in schema.nodes:
        chain = []
        parent = node.get("derive")
        while parent is not None:
            chain.append(parent)
            parent = schema.node_by_name(parent).get("derive")
        w.write(f'    {node["name"]}: [', ", ".join(f'"{p}"' for p in chain), "],\n")
    w.write("};\n\n")
    w.write(
        "export function isDerived(kind: NodeKind, base: NodeKind): boolean {\n"
        "    return kind === base || ANCESTORS[kind].includes(base);\n"
        "}\n"
        "\n"
    )


def _emit_fields(w: Writer, fields) -> None:
    for f in fields:
        w.write(f'    {f["name"]}: {_ts_type(f["type"])};\n')


def _emit_nodes(w: Writer, schema: Schema) -> None:
    for node in schema.nodes:
        parent = node.get("derive")
        w.write("export interface ", node["name"])
        if parent is not None:
            w.write(" extends ", parent)
        w.write(" {\n")
        _emit_fields(w, node["fields"])
        w.write("}\n\n")


def _emit_node_fields(w: Writer, schema: Schema) -> None:
    """ノード参照フィールドの一覧。所有辺だけを辿る走査 (traverse.h に当たる) 用。

    アリーナにはパーサが先読みして捨てたノードも残っているので、木から
    到達できるものだけを見たい場面 (hover など) はこれで所有辺を辿る。
    """
    w.write("export interface NodeFieldMeta {\n")
    w.write("    name: string;\n")
    w.write("    weak: boolean;\n")
    w.write("    list: boolean;\n")
    w.write("}\n\n")
    w.write("export const NODE_FIELDS: Readonly<Record<NodeKind, readonly NodeFieldMeta[]>> = {\n")
    for node in schema.nodes:
        entries = []
        for f in schema.all_fields(node):
            t = f["type"]
            is_list = bool(re.fullmatch(r"vector<Node<.+>>", t))
            if not is_list and not re.fullmatch(r"Node<.+>", t):
                continue
            weak = "true" if f.get("weak") else "false"
            entries.append(f'{{ name: "{f["name"]}", weak: {weak}, list: {str(is_list).lower()} }}')
        w.write(f'    {node["name"]}: [', ", ".join(entries), "],\n")
    w.write("};\n\n")


def _emit_structs(w: Writer, schema: Schema) -> None:
    for st in schema.structs:
        w.write("export interface ", st["name"], " {\n")
        _emit_fields(w, st["fields"])
        w.write("}\n\n")


def _emit_tables(w: Writer, schema: Schema) -> None:
    for table in schema.side_tables:
        if table.get("storage") == "flag":
            # 値を持たない。入っていること自体が答え。
            continue
        w.write("export interface ", table["name"], " {\n")
        _emit_fields(w, table["fields"])
        w.write("}\n\n")
    w.write("export const SIDE_TABLES = {\n")
    for table in schema.side_tables:
        w.write(
            f'    {table["name"]}: {{ over: "{table["over"]}", '
            f'storage: "{table.get("storage", "sparse")}" }},\n'
        )
    w.write("} as const;\n\n")


_RUNTIME = """export interface NodeHeader {
    type: NodeKind;
    data_index: number;
    loc: Loc;
}

export interface ArenaJSON {
    headers: NodeHeader[];
    [pool: string]: unknown;
}

export interface Diagnostic {
    msg: string;
    loc?: Loc;
    warn: boolean;
}

export interface DumpJSON {
    ok: boolean;
    main_file: number;
    root?: NodeId;
    modules?: NodeId[];
    diagnostics?: Diagnostic[];
    arena?: ArenaJSON;
    tables?: Record<string, Record<string, unknown>>;
}

export class Arena {
    constructor(private readonly json: ArenaJSON) {}

    count(): number {
        return this.json.headers.length;
    }

    header(id: NodeId): NodeHeader | null {
        const i = idIndex(id);
        if (i === 0 || i > this.json.headers.length) {
            return null;
        }
        return this.json.headers[i - 1];
    }

    kind(id: NodeId): NodeKind | null {
        return this.header(id)?.type ?? null;
    }

    loc(id: NodeId): Loc | null {
        return this.header(id)?.loc ?? null;
    }

    // NodeData<T>。フィールドは生成した interface の形をしている。
    data<T = unknown>(id: NodeId): T | null {
        const h = this.header(id);
        if (h === null) {
            return null;
        }
        const pool = this.json["data_" + h.type] as unknown[] | undefined;
        return (pool?.[h.data_index] ?? null) as T | null;
    }

    is(id: NodeId, base: NodeKind): boolean {
        const h = this.header(id);
        return h !== null && isDerived(h.type, base);
    }

    // 全ノードの unique_id を id 順に。
    *ids(): IterableIterator<NodeId> {
        for (let i = 0; i < this.json.headers.length; i++) {
            yield makeId(this.json.headers[i].type, i + 1);
        }
    }
}

// 所有辺だけを辿って、木から到達できるノードの id (下 32bit) を集める。
// アリーナには捨てられたノードも残っているので、生の全走査と区別する。
export function reachableFrom(arena: Arena, roots: readonly NodeId[]): Set<number> {
    const seen = new Set<number>();
    const stack: NodeId[] = [];
    const push = (id: unknown) => {
        if (typeof id !== "number") {
            return;
        }
        const i = idIndex(id);
        if (i === 0 || seen.has(i)) {
            return;
        }
        seen.add(i);
        stack.push(id);
    };
    for (const r of roots) {
        push(r);
    }
    while (stack.length > 0) {
        const id = stack.pop() as NodeId;
        const h = arena.header(id);
        if (h === null) {
            continue;
        }
        const data = arena.data<Record<string, unknown>>(id);
        if (data === null) {
            continue;
        }
        for (const f of NODE_FIELDS[h.type]) {
            if (f.weak) {
                continue;
            }
            const v = data[f.name];
            if (f.list) {
                for (const x of (v as unknown[] | undefined) ?? []) {
                    push(x);
                }
            }
            else {
                push(v);
            }
        }
    }
    return seen;
}

export class SideTables {
    constructor(private readonly json: Record<string, Record<string, unknown>>) {}

    get<T = unknown>(table: keyof typeof SIDE_TABLES, id: NodeId): T | undefined {
        return this.json[table]?.[String(idIndex(id))] as T | undefined;
    }

    has(table: keyof typeof SIDE_TABLES, id: NodeId): boolean {
        return this.get(table, id) !== undefined;
    }
}

export interface Dump {
    ok: boolean;
    mainFile: number;
    root: NodeId | null;
    modules: NodeId[];
    diagnostics: Diagnostic[];
    arena: Arena | null;
    tables: SideTables;
}

export function loadDump(json: DumpJSON): Dump {
    return {
        ok: json.ok,
        mainFile: json.main_file,
        root: json.root !== undefined && !isNullId(json.root) ? json.root : null,
        modules: json.modules ?? [],
        diagnostics: json.diagnostics ?? [],
        arena: json.arena !== undefined ? new Arena(json.arena) : null,
        tables: new SideTables(json.tables ?? {}),
    };
}
"""


def emit_ts(schema: Schema) -> str:
    w = Writer()
    w.write(PROLOGUE)
    _emit_prelude(w)
    _emit_enums(w, schema)
    _emit_enum_display(w, schema)
    _emit_kinds(w, schema)
    _emit_nodes(w, schema)
    _emit_node_fields(w, schema)
    _emit_structs(w, schema)
    _emit_tables(w, schema)
    w.write(_RUNTIME)
    return w.getvalue()
