#!/usr/bin/env python3
"""nast バックエンドを Web Playground に組み込むためのグルーを生成する。

rebrgen の ebmwebgen.py と同じ仕組み: 各 nast2<lang> の --show-flags を読んで
worker / caller / worker 登録を生成する。UI まわり (フラグ -> 引数、設定欄) は
ebmwebgen.py の ui_glue_code をそのまま使い、違うのは worker だけ
(nast は .bgn を自分で読むので、エディタの中身をそのまま /editor.bgn に書く)。

--show-flags は wasm 自身から node で読む。ネイティブのビルドが無くても
emscripten のビルド (build/web) だけで生成できる。

    python src/core/nast/nastwebgen.py <wasm-dir> <output-dir>

<wasm-dir>    nast2<lang>.js / .wasm がある場所 (emscripten ビルドの出力)
<output-dir>  生成先。wasm と js もここに写す (web/dev/src/lib/nast)

生成するもの:
    nast2<lang>_worker.js  EmWorkContext で wasm を回す worker
    nast_caller.js         NAST_LANGUAGES / generateNASTCode / setNASTUIConfig
    nast_workers.js        worker の登録 (nast_workers)
"""

import json
import os
import shutil
import subprocess
import sys

NAST_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.normpath(os.path.join(NAST_DIR, "..", "..", ".."))
sys.path.append(os.path.join(REPO_ROOT, "rebrgen", "script"))
from ebmwebgen import ui_glue_code, web_glue_names  # noqa: E402

HEADER = "/*license*/\n// Code generated by nastwebgen, DO NOT EDIT.\n"

# wasm の emscripten_main を node で 1 回呼んで stdout を返す。
SHOW_FLAGS_JS = """
const [modPath] = process.argv.slice(1);
const { pathToFileURL } = await import("node:url");
const factory = (await import(pathToFileURL(modPath).href)).default;
let out = "";
let err = "";
const m = await factory({ print: (t) => { out += t + "\\n"; }, printErr: (t) => { err += t + "\\n"; } });
const code = m.ccall("emscripten_main", "number", ["string"], ["nast2x --show-flags"]);
if (code !== 0) {
    process.stderr.write(err);
    process.exit(code || 1);
}
process.stdout.write(out);
"""


def backend_names() -> list[str]:
    root = os.path.join(NAST_DIR, "backends")
    return sorted(d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)))


def get_tools(wasm_dir: str) -> list[dict]:
    tools = []
    for lang in backend_names():
        js = os.path.join(wasm_dir, f"nast2{lang}.js")
        if not os.path.exists(js):
            continue
        out = subprocess.run(
            ["node", "--input-type=module", "-e", SHOW_FLAGS_JS, os.path.abspath(js)],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
        tools.append({"name": lang, "path": js, "flags": json.loads(out)})
    return tools


def worker_glue_code(web_glue: dict) -> str:
    worker = web_glue["worker_name"]
    return (
        HEADER
        + f'import * as nast from "./{worker}.js";\n'
        + 'import { EmWorkContext } from "../../s2j/em_work_ctx.js";\n'
        + "const nastModule = nast.default;\n"
        + "// nast reads the .bgn itself, so the request carries the editor text\n"
        + "// (not the src2json output). Imports come as extraSources, which\n"
        + "// EmWorkContext writes next to it.\n"
        + "const requestCallback = (e, m) => {\n"
        + "    switch (e.lang) {\n"
        + f'        case "{web_glue["ui_lang_name"]}":\n'
        + '            m.FS.writeFile("/editor.bgn", e.sourceCode);\n'
        + f'            return ["{worker}", "-i", "/editor.bgn"];\n'
        + "        default:\n"
        + '            return new Error("unknown message type");\n'
        + "    }\n"
        + "};\n"
        + "const nastWorker = new EmWorkContext(nastModule, requestCallback, () => {\n"
        + f'    console.log("{worker} worker is ready");\n'
        + "});\n"
    )


def generate(tools: list[dict], wasm_dir: str, output_dir: str) -> None:
    os.makedirs(output_dir, exist_ok=True)
    ui_glue = ""
    calls = ""
    sets = ""
    candidates = []
    lsp = {}
    workers = ""
    for tool in tools:
        g = web_glue_names(tool)
        worker = g["worker_name"]
        for ext in (".js", ".wasm"):
            shutil.copyfile(os.path.join(wasm_dir, worker + ext), os.path.join(output_dir, worker + ext))
        with open(os.path.join(output_dir, f"{worker}_worker.js"), "w", encoding="utf-8", newline="\n") as f:
            f.write(worker_glue_code(g))
        ui_glue += ui_glue_code(g, tool)
        calls += f'    case "{g["ui_lang_name"]}": return {g["call_worker_func"]}(factory,traceID,{g["call_ui_to_opt_func"]}(ui),sourceCode,ui.getExtraSources?.());\n'
        sets += f"  {g['call_set_ui_func']}(ui);\n"
        candidates.append(g["ui_lang_name"])
        lsp[g["ui_lang_name"]] = g["lsp_lang"]
        workers += f"    \"{worker}\": () => new Worker(new URL('./{worker}_worker.js', import.meta.url),{{type: \"module\"}}),\n"

    with open(os.path.join(output_dir, "nast_caller.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        f.write(ui_glue)
        f.write("export function generateNASTCode(factory,ui,traceID,lang,sourceCode) { switch(lang) {\n")
        f.write(calls)
        f.write("    default: throw new Error('Unsupported language: ' + lang);\n  }\n}\n")
        f.write(f"export const NAST_LANGUAGES = Object.freeze({json.dumps(candidates)});\n")
        f.write(f"export const NAST_LSP_LANGUAGES = Object.freeze({json.dumps(lsp)});\n")
        f.write("export function setNASTUIConfig(ui) {\n" + sets + "}\n")
    with open(os.path.join(output_dir, "nast_workers.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        f.write("export const nast_workers = Object.freeze({\n" + workers + "});\n")
    print(f"nastwebgen: {', '.join(candidates) or '(no backend)'} -> {output_dir}")


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: nastwebgen.py <wasm-dir> <output-dir>", file=sys.stderr)
        return 2
    wasm_dir, output_dir = sys.argv[1], sys.argv[2]
    tools = get_tools(wasm_dir)
    if not tools:
        print(f"nastwebgen: no nast2<lang>.js in {wasm_dir}", file=sys.stderr)
        return 1
    generate(tools, wasm_dir, output_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
